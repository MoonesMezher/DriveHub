def set_rtl_paragraph(paragraph, align_right=True):
    p_pr = paragraph._p.get_or_add_pPr()
    p_pr.append(OxmlElement("w:bidi"))
    if align_right:
        paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def set_rtl_run(run, bold=False, size=12, color=None):
    run.font.name = "Arial"
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = color
    r_pr = run._r.get_or_add_rPr()
    r_pr.append(OxmlElement("w:rtl"))
    r_fonts = OxmlElement("w:rFonts")
    r_fonts.set(qn("w:ascii"), "Arial")
    r_fonts.set(qn("w:hAnsi"), "Arial")
    r_fonts.set(qn("w:cs"), "Arial")
    r_pr.append(r_fonts)


def add_heading(doc, text, level=1):
    p = doc.add_paragraph()
    set_rtl_paragraph(p)
    sizes = {1: 22, 2: 16, 3: 14}
    run = p.add_run(text)
    set_rtl_run(run, bold=True, size=sizes.get(level, 12))
    if level == 1:
        run.font.color.rgb = RGBColor(0x1A, 0x47, 0x8C)
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)


def add_para(doc, text, bold=False, size=12, bullet=False):
    p = doc.add_paragraph(style="List Bullet" if bullet else None)
    set_rtl_paragraph(p)
    set_rtl_run(p.add_run(text), bold=bold, size=size)
    p.paragraph_format.space_after = Pt(4)


def add_code_block(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = p.add_run(text)
    run.font.name = "Consolas"
    run.font.size = Pt(9)
    p.paragraph_format.left_indent = Cm(0.5)
    p.paragraph_format.space_after = Pt(8)
    shading = OxmlElement("w:shd")
    shading.set(qn("w:fill"), "F5F5F5")
    p._p.get_or_add_pPr().append(shading)


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for i, h in enumerate(headers):
        p = table.rows[0].cells[i].paragraphs[0]
        set_rtl_paragraph(p)
        run = p.add_run(h)
        set_rtl_run(run, bold=True, size=11, color=RGBColor(0xFF, 0xFF, 0xFF))
        shading = OxmlElement("w:shd")
        shading.set(qn("w:fill"), "1A478C")
        table.rows[0].cells[i]._tc.get_or_add_tcPr().append(shading)
    for r_idx, row in enumerate(rows):
        for c_idx, cell_text in enumerate(row):
            p = table.rows[r_idx + 1].cells[c_idx].paragraphs[0]
            set_rtl_paragraph(p)
            set_rtl_run(p.add_run(str(cell_text)), size=10)
    if col_widths:
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()


