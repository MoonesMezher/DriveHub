const { makeHandler } = require('../utils/controllerFactory');
const {
    platformService,
    licenseService,
    faqService,
    requirementService,
    testimonialService,
    schoolApplicationService,
    reviewService,
    auditService,
    settingsService,
    paymentService,
    walletService,
} = require('../services');

module.exports = {
    listPricing: makeHandler(() => platformService.listPricing(), { wrap: (d) => ({ pricing: d }) }),
    upsertPricing: makeHandler((req) => platformService.upsertPricing(req.body, req._user.userId), { wrap: (d) => ({ pricing: d }) }),
    updateCommission: makeHandler((req) => platformService.updateCommission(req.body)),
    listLicenses: makeHandler(() => licenseService.listAdmin(), { wrap: (d) => ({ licenses: d }) }),
    upsertLicense: makeHandler((req) => licenseService.upsertCategory(req.body, req._user.userId), { wrap: (d) => ({ license: d }) }),
    upsertSubType: makeHandler((req) => licenseService.upsertSubType(req.body), { wrap: (d) => ({ subType: d }) }),
    listFaq: makeHandler(() => faqService.listAdmin(), { wrap: (d) => ({ items: d }) }),
    createFaq: makeHandler((req) => faqService.create(req.body, req._user.userId), { status: 201, wrap: (d) => ({ item: d }) }),
    updateFaq: makeHandler((req) => faqService.update(req.params.id, req.body, req._user.userId), { wrap: (d) => ({ item: d }) }),
    deleteFaq: makeHandler((req) => faqService.delete(req.params.id), { message: 'تم حذف السؤال' }),
    listRequirements: makeHandler((req) => requirementService.listAdmin(req.query.section), { wrap: (d) => ({ items: d }) }),
    createRequirement: makeHandler((req) => requirementService.create(req.body, req._user.userId), { status: 201, wrap: (d) => ({ item: d }) }),
    updateRequirement: makeHandler((req) => requirementService.update(req.params.id, req.body, req._user.userId), { wrap: (d) => ({ item: d }) }),
    deleteRequirement: makeHandler((req) => requirementService.delete(req.params.id), { message: 'تم حذف المتطلب' }),
    listTestimonials: makeHandler(() => testimonialService.listAdmin(), { wrap: (d) => ({ items: d }) }),
    createTestimonial: makeHandler((req) => testimonialService.create(req.body, req._user.userId), { status: 201, wrap: (d) => ({ item: d }) }),
    updateTestimonial: makeHandler((req) => testimonialService.update(req.params.id, req.body, req._user.userId), { wrap: (d) => ({ item: d }) }),
    deleteTestimonial: makeHandler((req) => testimonialService.delete(req.params.id), { message: 'تم حذف الرأي' }),
    listSchools: makeHandler((req) => platformService.listSchools(req.query), { wrap: (d) => ({ schools: d }) }),
    getSchool: makeHandler(
        (req) => platformService.getSchoolById(req.params.id),
        { wrap: (d) => ({ school: d }) },
    ),
    createSchool: makeHandler((req) => platformService.createSchool(req.body), { status: 201 }),
    updateSchool: makeHandler((req) => platformService.updateSchool(req.params.id, req.body)),
    deleteSchool: makeHandler((req) => platformService.deleteSchool(req.params.id)),
    listApplications: makeHandler((req) => schoolApplicationService.listPending(req.query), { wrap: (d) => ({ applications: d }) }),
    reviewApplication: makeHandler((req) => schoolApplicationService.review(req.params.id, req._user.userId, req.body)),
    listComplianceRequests: makeHandler(
        (req) => schoolApplicationService.listComplianceRequests(req.query),
        { wrap: (d) => ({ requests: d }) },
    ),
    getComplianceRequestById: makeHandler(
        (req) => schoolApplicationService.getComplianceRequestById(req.params.id),
        { wrap: (d) => ({ request: d }) },
    ),
    approveComplianceRequest: makeHandler(
        (req) => schoolApplicationService.approveComplianceRequest(req.params.id, req._user.userId),
        { message: 'تم قبول الطلب بنجاح' },
    ),
    rejectComplianceRequest: makeHandler(
        (req) => schoolApplicationService.rejectComplianceRequest(
            req.params.id,
            req._user.userId,
            req.body.rejectionReason,
        ),
        { message: 'تم رفض الطلب بنجاح' },
    ),
    listUsers: makeHandler((req) => platformService.listUsers(req.query), { wrap: (d) => ({ users: d }) }),
    getUser: makeHandler(
        (req) => platformService.getUserById(req.params.id),
        { wrap: (d) => ({ user: d }) },
    ),
    assignRole: makeHandler((req) => platformService.assignRole(req.body, req._user.userId), { status: 201 }),
    suspendUser: makeHandler((req) => platformService.suspendUser(req.params.id, req.body)),
    listAds: makeHandler(() => platformService.listAds(), { wrap: (d) => ({ ads: d }) }),
    createAd: makeHandler((req) => platformService.createAd(req._user.userId, req.body), { status: 201 }),
    updateAd: makeHandler((req) => platformService.updateAd(req.params.id, req.body)),
    distributeRosters: makeHandler((req) => platformService.distributeRosters(req.body)),
    listAudit: makeHandler((req) => auditService.getRecent(req.query.limit, req.query), { wrap: (d) => ({ logs: d }) }),
    reports: makeHandler((req) => platformService.getReports(req.query), { wrap: (d) => ({ reports: d }) }),
    listPendingReviews: makeHandler(() => reviewService.listPending(), { wrap: (d) => ({ reviews: d }) }),
    moderateReview: makeHandler((req) => reviewService.moderate(req.params.id, req._user.userId, req.body), { wrap: (d) => ({ review: d }) }),
    createTrafficAccount: makeHandler((req) => platformService.createTrafficAccount(req.body, req._user.userId), { status: 201 }),
    assignSchoolManager: makeHandler(
        (req) => platformService.assignSchoolManager(req.params.id, req.body, req._user.userId),
        { wrap: (d) => ({ school: d.school, manager: d.manager, created: d.created }) },
    ),
    getPrivacy: makeHandler(() => settingsService.getPrivacy()),
    updatePrivacy: makeHandler((req) => settingsService.updatePrivacy(req.body.content, req._user.userId)),
    getRegistrationSettings: makeHandler(() => settingsService.getRegistrationSettings()),
    updateRegistrationSettings: makeHandler(
        (req) => settingsService.updateRegistrationSettings(req.body, req._user.userId),
    ),
    confirmEnrollmentPayment: makeHandler(
        (req) => paymentService.confirmByStaff({
            enrollmentId: req.params.id,
            confirmedByUserId: req._user.userId,
            schoolScope: null,
            amount: req.body.amount,
            gatewayRef: req.body.gatewayRef,
        }),
        { message: 'تم تأكيد الدفع اليدوي بنجاح' },
    ),
    getUserWallet: makeHandler((req) => walletService.getWallet(req.params.id, req.query)),
    creditUserWallet: makeHandler(
        (req) => walletService.creditUser({
            userId: req.params.id,
            amount: req.body.amount,
            adminId: req._user.userId,
            note: req.body.note,
        }),
        { message: 'تم إضافة الرصيد بنجاح' },
    ),
};
